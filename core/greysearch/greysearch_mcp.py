"""Portable research stack (Windows source fallback).

Search is the two keyless lanes in tools.research_integration. Deep research
adds page text from the local browser service, one page at a time, inside the
same time budget the compiled stack uses. It reports exactly which pages were
rejected and never invents content.
"""
from __future__ import annotations

import json
import re
import time
from pathlib import Path


def research_search(query: str = "", max_results: int = 10, **kw) -> dict:
    from tools.research_integration import research_search as _search
    r = _search(query, max_results=max_results)
    r.setdefault("trust", "high")
    return r


def _slug(query: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", (query or "").lower()).strip("-")
    return (text or "guide")[:60]


def _resolve_guide_path(spec, query: str, slug_tag: str = "") -> Path:
    root = Path(__file__).resolve().parent / "guides"
    root.mkdir(parents=True, exist_ok=True)
    return root / (_slug(query) + (("-" + slug_tag) if slug_tag else "") + ".md")


def _attach_guide(result: dict, query: str, write_path: Path) -> dict:
    sources = result.get("sources") or []
    lines = ["# Research guide: %s" % query, "",
             "Generated by the portable research stack.", ""]
    for index, source in enumerate(sources, 1):
        lines.append("## %d. %s" % (index, source.get("title") or source.get("url")))
        lines.append("")
        lines.append(source.get("url", ""))
        lines.append("")
        text = (source.get("text") or "").strip()
        if text:
            lines.append(text[:1500])
            lines.append("")
    try:
        write_path.write_text("\n".join(lines), encoding="utf-8")
        result["master_guide"] = {"path": str(write_path)}
    except OSError as exc:
        result["guide_error"] = str(exc)[:200]
    return result


def research_deep(question: str = "", max_pages: int = 2,
                  max_total_seconds: int = 240, enable_semantic_judge: bool = True,
                  min_accept_score: int = 35, **kw) -> dict:
    q = str(question or "").strip()
    if not q:
        raise ValueError("missing question")
    pages = max(1, min(int(max_pages or 2), 6))
    deadline = time.time() + max(30, int(max_total_seconds or 240))
    search = research_search(q, max_results=max(3, pages * 3))
    results = search.get("results") or []
    sources, rejected = [], []
    budget_hit = False
    from services import browser_mcp as browser
    for item in results:
        if len(sources) >= pages:
            break
        if time.time() > deadline:
            budget_hit = True
            break
        url = item.get("url") or ""
        try:
            page = browser.dispatch("browser_open", {"url": url})
        except Exception as exc:
            rejected.append({"url": url, "reason": str(exc)[:160]})
            continue
        if not isinstance(page, dict) or page.get("error"):
            rejected.append({"url": url,
                             "reason": str((page or {}).get("error") or "no page")[:160]})
            continue
        text = (page.get("text") or "").strip()
        if not text:
            rejected.append({"url": url, "reason": "empty page text"})
            continue
        sources.append({
            "url": page.get("url_final") or url,
            "title": page.get("title") or item.get("title") or "",
            "snippet": item.get("snippet") or "",
            "text": text[:6000],
            "score": 50,
        })
    run_report = {
        "engine": search.get("engine"),
        "queries": 1,
        "candidates": len(results),
        "pages_fetched": len(sources) + len(rejected),
        "accepted": len(sources),
        "elapsed_s": round(time.time() - (deadline - max_total_seconds), 1),
    }
    return {
        "sources": sources,
        "facts": [],
        "rejected_pages": rejected,
        "quarantined_pages": [],
        "run_report": run_report,
        "budget_hit": budget_hit,
        "judge_ran": False,
        "mode": "portable",
    }


def dispatch(name: str, args: dict) -> dict:
    args = args or {}
    if name in ("greysearch_health", "research_health"):
        return {"mode": "portable", "search_lanes": ["bing-rss", "ddg-html"],
                "browser": "services.browser_mcp", "judge": False}
    if name == "research_search":
        return research_search(args.get("query") or args.get("q") or "",
                               max_results=int(args.get("max_results") or 10))
    if name == "research_deep":
        return research_deep(args.get("query") or args.get("question") or "",
                             max_pages=int(args.get("max_pages") or 2),
                             max_total_seconds=int(args.get("max_total_seconds") or 240))
    raise KeyError(name)
